"""Basic arithmetic operations for the Lambda function."""


def add(a, b):
    """Return the sum of two values."""
    return a + b


def subtract(a, b):
    """Subtract the second value from the first."""
    return a - b


def divide(a, b):
    """Divide the first value by the second."""
    return a / b


def multiply(a, b):
    """Return the product of two values."""
    return a * b
